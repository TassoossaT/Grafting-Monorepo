import { outwardPerimeterRings } from "../../../../features/edit-construction/index.ts";
import { constraintsFromRings, type ConstraintRing } from "./terrain-constraints.ts";
import { fillTerrain, type TerrainFillRuntime } from "./terrain-fill.ts";

/**
 * Terrain's own answer to `resolveCutRepair`'s `"regenerate"`: grow the ground
 * back around the thing that cut it.
 *
 * **What this is, in one line:** the area the cut consumed is regenerated by
 * the same call that lays terrain in the first place
 * (`fillTerrain`, `terrain-fill.ts`), bounded by the rim the removal exposed
 * and holed by the painter's own contour.
 *
 * **Why the rim and the contour both go down as constraints.** The hole a cut
 * leaves is bounded on one side by the terrain that survived and on the other
 * by the road standing in the middle of it. Handing the generator only the
 * outer rim lays ground straight across the road -- the two banks joined over
 * the top of the path, which is exactly what the table saw. Both sides carry
 * their own node ids, so the ground that comes back shares real nodes and real
 * edges with the terrain it grew from *and* with the road it stops at: one
 * graph, terrain-road-terrain, without either side welding onto the other.
 *
 * **What is deliberately absent.** No polygon difference, no ear clipping, no
 * proximity weld, no gap-filling pass afterwards. Every earlier repair
 * computed the shape of the hole independently of the graph and then had to
 * reconcile the two: vertices minted on top of nodes that already existed, a
 * seam declaring one edge where the neighbour had three, faces wound against
 * the only free side their neighbour left. None of those are handled here
 * because none can arise -- the graph is the input, not something the result
 * has to be made to agree with afterwards.
 *
 * **What comes back is not what was there.** The mesh is regenerated, not
 * restored, so a road drawn and erased leaves terrain of a different shape
 * than before. That is the accepted trade: no shadow copy of the ground a cut
 * removed has to be kept anywhere for a road to stay reversible.
 */
export interface TerrainCutRepairRuntime extends TerrainFillRuntime {
  getRegionTopology(surfaceKey: ConstructionSurfaceKey): ConstructionRegionTopology | undefined;
}

/** How wide a cell the regrown ground uses -- the same scale the sculpt brush lays. */
const TRIANGLE_SIDE = 2;

/**
 * Height for a corner the regeneration invents, blended from the ring nodes
 * around it by inverse square distance.
 *
 * Not the noise field the sculpt brush samples: this ground has to *continue*
 * terrain that already stands at a settled height, and a fresh noise sample
 * would step away from the rim it meets. Blending from the rim and the road
 * instead means the fill arrives already agreeing with both at its edges,
 * which is the only place it is pinned.
 */
function blendedHeight(
  anchors: readonly ConstructionPosition[],
  point: { readonly x: number; readonly z: number },
): number {
  let weighted = 0;
  let total = 0;
  for (const anchor of anchors) {
    const dx = anchor.x - point.x;
    const dz = anchor.z - point.z;
    const distanceSq = dx * dx + dz * dz;
    // Sitting on an anchor is that anchor's height, not a division by zero.
    if (distanceSq < 1e-9) return anchor.y;
    const weight = 1 / distanceSq;
    weighted += anchor.y * weight;
    total += weight;
  }
  return total > 0 ? weighted / total : 0;
}

/**
 * Drops what the deletion took with it.
 *
 * A rim node shared with terrain that survived is still there; one belonging
 * only to faces this repair just deleted is gone. The *position* stays either
 * way -- the shape of the hole did not change -- but a point that no longer
 * names a live node is an ordinary point, and an edge missing an endpoint is
 * an edge nothing can split.
 */
function pruneToLive(
  rings: readonly ConstraintRing[],
  sources: readonly ConstructionNodeId[],
  isLive: (nodeId: ConstructionNodeId) => boolean,
): readonly ConstraintRing[] {
  const livePoint = (source: number | undefined): boolean => {
    if (source === undefined) return false;
    const nodeId = sources[source];
    return nodeId !== undefined && isLive(nodeId);
  };
  return rings.map((ring) => ({
    points: ring.points.map((point) => (livePoint(point.source) ? point : { x: point.x, z: point.z })),
    edges: ring.edges.map((edge, index) =>
      edge !== undefined && livePoint(ring.points[index]?.source) && livePoint(ring.points[(index + 1) % ring.points.length]?.source)
        ? edge
        : undefined,
    ),
  }));
}

/** Terrain's `CutRepairExecutor`. Returns the number of faces it managed to lay. */
export function repairTerrainCut(
  runtime: TerrainCutRepairRuntime,
  fallout: CutFallout,
  causeId: string,
  tableId: string,
): number {
  if (fallout.consumedSurfaceKeys.length === 0) return 0;

  // Read before deleting: the rim of the hole is the perimeter of the faces
  // about to go, and it is knowable only while they still stand.
  const consumed = fallout.consumedSurfaceKeys
    .map((surfaceKey) => runtime.getRegionTopology(surfaceKey))
    .filter((topology): topology is ConstructionRegionTopology => topology !== undefined);
  if (consumed.length === 0) return 0;
  const surfaceType = consumed[0]!.surfaceType;

  const consumedPositions = new Map<ConstructionNodeId, ConstructionPosition>();
  for (const topology of consumed) {
    for (const node of topology.nodes) consumedPositions.set(node.id, node.position);
  }
  const paintedPositions = new Map<ConstructionNodeId, ConstructionPosition>();
  for (const node of fallout.paintedNodes) paintedPositions.set(node.id, node.position);

  // One numbering across both lists, because the generator answers with a
  // single `source` index per corner and knows nothing of which ring it came
  // from.
  const rim = constraintsFromRings(
    outwardPerimeterRings(consumed),
    (nodeId) => consumedPositions.get(nodeId),
    0,
  );
  const road = constraintsFromRings(
    fallout.paintedLoops,
    (nodeId) => paintedPositions.get(nodeId),
    rim.sources.length,
  );
  if (rim.rings.length === 0) return 0;
  const sources = [...rim.sources, ...road.sources];

  // One region at a time: a key the engine no longer knows -- a face some
  // other repair in the same stroke already took -- is that key's own problem,
  // never a reason to leave the rest of the cut standing under the painter.
  let deleted = 0;
  for (const surfaceKey of fallout.consumedSurfaceKeys) {
    try {
      runtime.applyRegionEdit([{ kind: "delete-region", surfaceKey }], "local", causeId);
      deleted += 1;
    } catch {
      // Counted by its absence; the rim prune below sees the consequence.
    }
  }
  if (deleted === 0) return 0;

  const stamp = Math.abs(hashOf(fallout.consumedSurfaceKeys));
  const live = runtime.getSnapshot().map.nodePositions;
  const boundary = pruneToLive(rim.rings, sources, (nodeId) => live.has(nodeId));

  const anchors = [
    ...[...consumedPositions].filter(([nodeId]) => live.has(nodeId)).map(([, position]) => position),
    ...paintedPositions.values(),
  ];

  return fillTerrain(runtime, {
    // Deterministic in the hole itself rather than in the clock, so the same
    // cut repaired twice produces the same ground and the same ids: a repair
    // is replayable from the same log.
    mint: `${causeId}:repair-${stamp}`,
    tableId,
    causeId,
    seed: Math.max(1, stamp),
    triangleSide: TRIANGLE_SIDE,
    // The consumed type, so a cut through slate comes back slate without this
    // side having to know that.
    surfaceType,
    boundary,
    holes: road.rings,
    sources,
    heightAt: (point) => blendedHeight(anchors, point),
  }).built;
}

/** A stable small integer for a set of keys -- a seed, not a checksum. */
function hashOf(keys: readonly ConstructionSurfaceKey[]): number {
  let hash = 2166136261;
  for (const key of keys) {
    for (const part of key) {
      for (let index = 0; index < part.length; index += 1) {
        hash ^= part.charCodeAt(index);
        hash = Math.imul(hash, 16777619);
      }
    }
  }
  return hash | 0;
}
