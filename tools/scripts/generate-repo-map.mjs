// G-003 (master source S17/S23): a reproducible, derived map of every
// real Nx project in the workspace, grouped by ecosystem tag. Mirrors
// generate-graph-ir.mjs's established shape (plain Node ESM, no
// dependencies beyond built-ins, deterministic output, a --check flag
// that diffs against the committed file and exits non-zero on drift) --
// not a new convention.

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const outputPath = resolve(root, "docs/generated/repo-map.md");
const check = process.argv.includes("--check");

const readJson = async (relative) => JSON.parse(await readFile(resolve(root, relative), "utf8"));

const graph = (await readJson("docs/generated/project-graph.json")).graph;

// One canonical ecosystem label per known tag prefix; anything untagged
// (or tagged with something this list doesn't know about) is honestly
// grouped as "Other" rather than silently dropped.
const ECOSYSTEM_ORDER = ["lang:rust", "lang:csharp", "lang:typescript", "lang:python", "Other"];
const ECOSYSTEM_LABEL = {
  "lang:rust": "Rust",
  "lang:csharp": "C# / .NET",
  "lang:typescript": "TypeScript",
  "lang:python": "Python",
  Other: "Other",
};

const projects = Object.entries(graph.nodes)
  .map(([name, node]) => {
    const tags = [...(node.data.tags ?? [])].sort();
    const ecosystem = ECOSYSTEM_ORDER.find((tag) => tags.includes(tag)) ?? "Other";
    const targets = Object.keys(node.data.targets ?? {}).sort();
    return {
      name,
      ecosystem,
      type: node.data.projectType ?? node.type ?? "unknown",
      root: node.data.root ?? ".",
      tags,
      targets,
    };
  })
  .sort((left, right) => left.name.localeCompare(right.name));

const lines = [];
lines.push("<!-- @generated by tools/scripts/generate-repo-map.mjs -- do not hand-edit. -->");
lines.push("# Repo map");
lines.push("");
lines.push(
  "Derived from `docs/generated/project-graph.json` (G-003, master source " +
    "S16.1/S17/S23). Regenerate with `pnpm graph:map`; `pnpm graph:map:check` " +
    "fails if this file is stale.",
);
lines.push("");

for (const ecosystem of ECOSYSTEM_ORDER) {
  const group = projects.filter((project) => project.ecosystem === ecosystem);
  if (group.length === 0) continue;

  lines.push(`## ${ECOSYSTEM_LABEL[ecosystem]}`);
  lines.push("");
  lines.push("| Project | Type | Root | Targets |");
  lines.push("| --- | --- | --- | --- |");
  for (const project of group) {
    lines.push(
      `| \`${project.name}\` | ${project.type} | \`${project.root}\` | ${project.targets.map((t) => `\`${t}\``).join(", ") || "—"} |`,
    );
  }
  lines.push("");
}

lines.push(`_${projects.length} project(s) total._`);

const rendered = `${lines.join("\n")}\n`;

if (check) {
  const existing = await readFile(outputPath, "utf8");
  if (existing !== rendered) throw new Error("repo-map.md is stale; run `pnpm graph:map`");
  console.log(`repo-map.md is current: ${projects.length} projects`);
} else {
  await writeFile(outputPath, rendered);
  console.log(`Generated ${outputPath}: ${projects.length} projects`);
}
